// Opt-in stock PrusaSlicer acceptance. Uses only generated /tmp files and an isolated datadir.
// PRUSASLICER_REAL_TEST=/path/to/PrusaSlicer node --test test/test-slice-real.js
// Python 3 is used only to assemble the synthetic project ZIP.
import test from 'node:test';
import assert from 'node:assert/strict';
import { writeFile, readFile, mkdir, stat, unlink } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createHash } from 'node:crypto';
import { runPrusaSlicer } from '../build/prusa-cli.js';
import { fixture, tool, text } from './slice-fixtures.js';
const exec = promisify(execFile);
const executablePath = process.env.PRUSASLICER_REAL_TEST;

test('stock 2.9.6: INI and 3MF scripts disabled; configured ID alone executes marker', { skip: !executablePath, timeout: 120000 }, async t => {
  const f = await fixture(t);
  const datadir = join(f.dir, 'isolated data');
  await mkdir(datadir);
  const { stdout: version } = await exec(executablePath, ['--help', '--datadir', datadir]);
  assert.match(version, /PrusaSlicer-2\.9\.6/);
  t.diagnostic(`${version.split('\n')[0]}; ${process.platform}/${process.arch}; fixture ${f.dir}`);
  const generator = (await readFile(new URL('./create-test-stl.js', import.meta.url), 'utf8')).replace('join(__dirname, "cube.stl")', 'process.argv[2]');
  const generatorPath = join(f.dir, 'generate.mjs');
  await writeFile(generatorPath, generator);
  await exec(process.execPath, [generatorPath, f.input]);
  const marker = join(f.dir, 'marker');
  const markerScript = join(f.dir, 'marker.mjs');
  await writeFile(markerScript, `import { appendFileSync } from 'node:fs'; appendFileSync(${JSON.stringify(marker)}, 'ran\\n');`);
  const command = `"${process.execPath}" "${markerScript}"`;
  const ini = join(f.dir, 'imported.ini');
  await writeFile(ini, `layer_height = 0.3\nfill_density = 0%\npost_process = ${JSON.stringify(command)}\n`);
  const project = join(f.dir, 'project.3mf');
  const assemble = `import sys,zipfile,struct,xml.sax.saxutils as x
stl,ini,out=sys.argv[1:]
b=open(stl,'rb').read(); vertices=[]; triangles=[]
for i in range(struct.unpack_from('<I',b,80)[0]):
 p=struct.unpack_from('<9f',b,84+i*50+12); n=len(vertices)
 vertices.extend([p[j:j+3] for j in (0,3,6)]); triangles.append((n,n+1,n+2))
model='<model unit="millimeter" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"><metadata name="Application">PrusaSlicer-2.9.6</metadata><resources><object id="1" type="model"><mesh><vertices>'+''.join('<vertex x="%s" y="%s" z="%s"/>'%v for v in vertices)+'</vertices><triangles>'+''.join('<triangle v1="%s" v2="%s" v3="%s"/>'%v for v in triangles)+'</triangles></mesh></object></resources><build><item objectid="1"/></build></model>'
with zipfile.ZipFile(out,'w') as z:
 z.writestr('[Content_Types].xml','<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/></Types>')
 z.writestr('_rels/.rels','<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Target="/3D/3dmodel.model" Id="rel0" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>')
 z.writestr('3D/3dmodel.model',model)
 z.writestr('Metadata/Slic3r_PE.config','; generated by PrusaSlicer 2.9.6\\n'+'\\n'.join('; '+line for line in open(ini).read().splitlines())+'\\n')
`;
  await exec('python3', ['-c', assemble, f.input, ini, project]);
  const config = { executablePath, profilesDir: '', trustedScripts: { marker: command } };
  const slice = tool((config, args, timeout, id) => runPrusaSlicer(config, [...args, '--datadir', datadir, '--threads', '2'], timeout, id), config);
  for (const [name, input] of [['ini', { stl_path: f.input, config_path: ini }], ['3mf', { stl_path: project }]]) {
    // Positive control: prove the imported fixture script is executable before testing its override.
    const controlArgs = ['--export-gcode', '--datadir', datadir, '--threads', '2', '--output', join(f.dir, `${name}-control.gcode`)];
    if (input.config_path) controlArgs.push('--load', input.config_path);
    controlArgs.push(input.stl_path);
    await new Promise((resolve, reject) => {
      const child = execFile(executablePath, controlArgs, { timeout: 30000 }, (error) => error ? reject(error) : resolve());
      child.stdin.end('Y\n');
    });
    assert.equal(await readFile(marker, 'utf8'), 'ran\n');
    await unlink(marker);
    const output = join(f.dir, `${name}.gcode`);
    const r = await slice({ ...input, output_gcode: output });
    assert.notEqual(r.isError, true, text(r));
    assert.ok((await stat(output)).size > 0);
    assert.equal(existsSync(marker), false);
    const trustedOutput = join(f.dir, `${name}-trusted.gcode`);
    const trusted = await slice({ ...input, output_gcode: trustedOutput, trusted_script_id: 'marker' });
    assert.notEqual(trusted.isError, true, text(trusted));
    assert.match(text(trusted), /trusted:marker/);
    assert.doesNotMatch(text(trusted), /marker\.mjs/);
    assert.equal(await readFile(marker, 'utf8'), 'ran\n');
    // Remove only this generated marker before the next default-mode check.
    if (name === 'ini') {
      await unlink(marker);
    }
    t.diagnostic(`${name}: native inherited script positive control passed; disabled has no marker; selected trusted ID writes marker; output bytes=${(await stat(output)).size}`);
  }
  for (const path of [f.input, ini, project]) t.diagnostic(`SHA256 ${path}: ${createHash('sha256').update(await readFile(path)).digest('hex')}`);
});
