import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { entries, model, mesh, writeFixture } from "./project-fixtures.js";
import { readProjectMetadata } from "../build/project-metadata.js";
import { parse3mf } from "../build/threemf-parser.js";
export const config =
  '<config><object id="1"><metadata type="object" key="name" value="Three parts"/><metadata type="object" key="perimeters" value="4"/><volume firstid="0" lastid="3"><metadata type="volume" key="volume_type" value="ModelPart"/><metadata type="volume" key="extruder" value="2"/></volume><volume firstid="4" lastid="7"><metadata type="volume" key="volume_type" value="NegativeVolume"/></volume><volume firstid="8" lastid="11"><metadata type="volume" key="volume_type" value="ParameterModifier"/><metadata type="volume" key="fill_density" value="50%"/></volume></object></config>';
test("native metadata preserves roles and overrides, excludes modifiers from mesh volume input", async (t) => {
  const dir = await mkdtemp(join(tmpdir(), "3mf-meta-"));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const triple = mesh.replace(
    "</triangles>",
    mesh.split("<triangles>")[1].split("</triangles>")[0].repeat(2) +
      "</triangles>",
  );
  const p = await writeFixture(
    join(dir, "m.3mf"),
    entries(model(`<object id="1">${triple}</object>`), {
      "Metadata/Slic3r_PE_model.config": config,
      "Metadata/Slic3r_PE.config":
        "; generated by PrusaSlicer\n; layer_height = 0.17\n; post_process = secret\n; printhost_apikey = secret\n",
    }),
  );
  const m = await readProjectMetadata(p);
  assert.deepEqual(
    m.objects[0].volumes.map((v) => v.role),
    ["ModelPart", "NegativeVolume", "ParameterModifier"],
  );
  assert.equal(m.objects[0].volumes[0].extruder_index, 1);
  assert.ok(
    m.stored_overrides.some(
      (s) =>
        s.address.target_id === "object:1/volume:2" &&
        s.address.key === "fill_density" &&
        s.value === "50%",
    ),
  );
  assert.equal(m.effective_configuration, null);
  assert.ok(m.stored_overrides.every((s) => s.effective_known === false));
  assert.equal(JSON.stringify(m).includes("secret"), false);
  assert.equal((await parse3mf(p)).triangles.length, 4);
});
test("painting, layers, text/svg and SLA are presence-only opaque descriptors", async (t) => {
  const dir = await mkdtemp(join(tmpdir(), "3mf-opaque-"));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const xml = model(
    `<object id="1">${mesh.replace("<triangle v3", '<triangle slic3rpe:custom_supports="opaque" v3')}</object>`,
    undefined,
    'xmlns:slic3rpe="http://schemas.slic3r.org/3mf/2017/06"',
  );
  const p = await writeFixture(
    join(dir, "m.3mf"),
    entries(xml, {
      "Metadata/Slic3r_PE_layer_heights_profile.txt": "opaque",
      "Metadata/Slic3r_PE_sla_support_points.txt": "opaque",
      "3D/shape.svg": "<svg/>",
      "Metadata/Slic3r_PE_model.config":
        '<config xmlns:slic3rpe="http://schemas.slic3r.org/3mf/2017/06"><object id="1"><volume firstid="0" lastid="3"><slic3rpe:text text="Example"/></volume></object></config>',
    }),
  );
  const m = await readProjectMetadata(p);
  assert.equal(m.coverage, "partial");
  for (const kind of ["painting", "variable_layers", "sla", "text", "svg"])
    assert.ok(m.opaque.some((o) => o.kind === kind));
});
test("stock 2.9.6 saved fixture retains native roles, object overrides and variable layers", async (t) => {
  const { readFile } = await import("node:fs/promises");
  const dir = await mkdtemp(join(tmpdir(), "3mf-native-"));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const data = JSON.parse(
    await readFile(
      new URL("./fixtures/native-2.9.6-project.json", import.meta.url),
      "utf8",
    ),
  );
  const p = await writeFixture(join(dir, "native.3mf"), data);
  const m = await readProjectMetadata(p);
  assert.deepEqual(
    m.objects[0].volumes.map((v) => v.role),
    ["ModelPart", "NegativeVolume", "ParameterModifier"],
  );
  assert.ok(
    m.stored_overrides.some(
      (s) =>
        s.address.scope === "object" &&
        s.address.key === "layer_height" &&
        s.value === "0.19",
    ),
  );
  assert.ok(
    m.stored_overrides.some(
      (s) =>
        s.address.scope === "volume" &&
        s.address.key === "fill_density" &&
        s.value === "42%",
    ),
  );
  assert.ok(m.opaque.some((o) => o.kind === "variable_layers"));
  assert.equal((await parse3mf(p)).triangles.length, 12);
});
